# 定义函数时括号里面的参数是形式参数（形参），
# 表明函数声明将要使用参数
def add(x,y):
    result = x + y
    print(f"{x} + {y}的计算结果是{x + y}")


# 函数调用时括号里的参数时实际参数（实参），
# 表示函数执行时真正使用的参数值
add(3,6)


