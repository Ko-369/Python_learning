# 算数运算符
print("1+1 = ",1+1)
print("2-1 = ",2-1)
print("3*3 = ",3*3)
print("6/2 = ",6/2)
print("11//2 = ",11//2)
print("9%2 = ",9%2)
print("2**2 = ",2**2)

