# 根据下标索引取特定位置的数据
# 下标索引的值是从0开始的
# 语法： 列表[下标索引]
my_list = ["Tom","Lily","Rose"]
# 列表[下标索引]，从前向后从0开始，每次+1，从后向前从-1开始，每次-1
print(my_list[0])
print(my_list[1])
print(my_list[2])

# 倒序取出列表元素
print(my_list[-1])
print(my_list[-2])
print(my_list[-3])

my_list = [[1,2,3],[4,5,6]]
# 取出嵌套列表的元素
print(my_list[1][2])



